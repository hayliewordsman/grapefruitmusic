"""Generate the shared Java palette and Android app resources from one catalog."""
import argparse
import json
from pathlib import Path
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[2]
ROLES = {
    "background": "background", "on_background": "text",
    "surface": "background", "surface_dim": "background",
    "surface_bright": "control", "surface_container_lowest": "background",
    "surface_container_low": "bar", "surface_container": "surface",
    "surface_container_high": "control", "surface_container_highest": "control_pressed",
    "surface_variant": "control", "on_surface": "text",
    "on_surface_variant": "text_secondary", "primary": "accent",
    "on_primary": "on_accent", "primary_container": "control",
    "on_primary_container": "text", "surface_tint": "accent",
    "control_activated": "accent", "control_normal": "text_secondary",
    "outline": "text_secondary", "outline_variant": "outline",
}
ATTRS = {
    "gfBackground": "background", "gfGroupedBackground": "grouped",
    "gfSurface": "surface", "gfBar": "bar", "gfTextPrimary": "text",
    "gfTextSecondary": "text_secondary", "gfSeparator": "separator",
    "gfDisclosure": "disclosure", "gfAccent": "accent", "gfFill": "fill",
    "gfScrim": "scrim", "gfControl": "control", "gfControlPressed": "control_pressed",
    "gfToggleOff": "toggle_off", "gfToggleOffSegments": "toggle_off_segments",
    "gfKnob": "knob", "gfAccentEnd": "accent_end", "gfOnAccent": "on_accent",
    "gfOutline": "outline",
}


def java_color(value):
    return "0x" + ("ff" if len(value) == 7 else "") + value[1:].lower()


def keyboard_outputs():
    result = {}
    aliases = {
        "grapefruit_keyboard_background": "background",
        "grapefruit_keyboard_surface": "surface_container",
        "grapefruit_key_fill": "surface_container_high",
        "grapefruit_key_down": "surface_container_highest",
        "grapefruit_key_outline": "outline_variant",
        "grapefruit_key_text": "on_surface",
        "grapefruit_key_secondary": "on_surface_variant",
        "grapefruit_key_accent": "primary",
    }
    for mode, directory in [("light", "values"), ("dark", "values-night")]:
        res = ET.Element("resources")
        for name, role in aliases.items():
            ET.SubElement(res, "color", name=name).text = "@android:color/system_" + role + "_" + mode
        if directory == "values":
            ET.SubElement(res, "string", name="grapefruit_keyboard_theme").text = "Grapefruit theme"
            ET.SubElement(res, "string", name="grapefruit_keyboard_follows_system").text = "Follows your system theme"
        ET.indent(res)
        result[f"os/platform/latinime/res/{directory}/grapefruit.xml"] = ET.tostring(res, encoding="unicode") + "\n"
    ns = 'xmlns:android="http://schemas.android.com/apk/res/android"'
    for name, fill, outline, width in [
        ("normal", "fill", "outline", "1dp"),
        ("pressed", "down", "accent", "1dp"),
        ("action", "fill", "accent", "1dp"),
        ("selected", "down", "accent", "2dp"),
    ]:
        # Insets change paint only; the AOSP keyboard's key geometry and touch regions stay intact.
        result[f"os/platform/latinime/res/drawable/grapefruit_key_{name}.xml"] = (
            f'<inset {ns} android:insetLeft="2dp" android:insetTop="2dp" android:insetRight="2dp" android:insetBottom="2dp">'
            f'<shape><solid android:color="@color/grapefruit_key_{fill}"/>'
            f'<stroke android:width="{width}" android:color="@color/grapefruit_key_{outline}"/>'
            '<corners android:radius="24dp" android:bottomRightRadius="4dp"/></shape></inset>\n')
    for name, default in [("grapefruit_key", "normal"), ("grapefruit_action_key", "action")]:
        result[f"os/platform/latinime/res/drawable/{name}.xml"] = (
            f'<selector {ns}>'
            '<item android:state_empty="true" android:drawable="@android:color/transparent"/>'
            '<item android:state_pressed="true" android:drawable="@drawable/grapefruit_key_pressed"/>'
            '<item android:state_checked="true" android:drawable="@drawable/grapefruit_key_selected"/>'
            '<item android:state_active="true" android:drawable="@drawable/grapefruit_key_selected"/>'
            '<item android:state_focused="true" android:drawable="@drawable/grapefruit_key_selected"/>'
            f'<item android:drawable="@drawable/grapefruit_key_{default}"/></selector>\n')
    return result


def outputs():
    themes = json.loads((ROOT / "os/themes/catalog.json").read_text())["themes"]
    edition = json.loads((ROOT / "os/edition.json").read_text())
    lines = ["// Generated by os/tools/generate.py. SPDX-License-Identifier: Apache-2.0",
             "package com.grapefruit.os.theme;", "", "public final class GrapefruitPalette {",
             "    private GrapefruitPalette() {}",
             "    public static int valid(int id) { return id >= 0 && id < 4 ? id : 0; }",
             "    public static boolean dark(int id) { return valid(id) != 1; }"]
    for method, role in [("seed", "accent"), ("background", "background")]:
        values = ", ".join(java_color(t["colors"][role]) for t in themes)
        lines += [f"    private static final int[] {method.upper()} = {{{values}}};",
                  f"    public static int {method}(int id) {{ return {method.upper()}[valid(id)]; }}"]
    lines += ["    public static int role(int id, String role, boolean dark, double contrast, int fallback) {",
              "        id = valid(id);",
              "        // Leave opposite-mode and accessibility contrast generation to Android's HCT engine.",
              "        if (dark != dark(id) || Math.abs(contrast) > 0.0001) return fallback;",
              "        switch (role) {"]
    for name, key in ROLES.items():
        values = ", ".join(java_color(t["colors"][key]) for t in themes)
        lines.append(f'            case "{name}": return new int[]{{{values}}}[id];')
    lines += ["            default: return fallback;", "        }", "    }", "}", ""]
    result = {"os/generated/GrapefruitPalette.java": "\n".join(lines)}
    # Separate resource names avoid Blue's build-time overrides of the original Audio palette.
    res = ET.Element("resources")
    for t in themes:
        n, c = t["id"], t["colors"]
        ET.SubElement(res, "color", name=f"os_background_{n}").text = c["background"]
        style = ET.SubElement(res, "style", name=f"Theme.Grapefruit.OS{n}",
                              parent="Theme.Grapefruit.GrapefruitLight" if n == 1 else "Theme.Grapefruit.GrapefruitDark")
        for attr, key in ATTRS.items():
            ET.SubElement(style, "item", name=attr).text = c[key]
        for attr, value in {
            "android:windowBackground": c["background"], "android:colorBackground": c["background"],
            "android:textColorHighlight": "#66" + c["accent"][1:],
            "gfSplash": f"@color/os_background_{n}", "gfFieldBackground": f"@drawable/os_field_{n}",
            "android:editTextStyle": f"@style/GrapefruitEditText.OS{n}",
        }.items():
            ET.SubElement(style, "item", name=attr).text = value
        field = ET.SubElement(res, "style", name=f"GrapefruitEditText.OS{n}", parent="android:Widget.Holo.EditText")
        for attr, val in {"android:background": f"@drawable/os_field_{n}", "android:textColor": c["text"],
                          "android:textColorHint": c["text_secondary"],
                          "android:textCursorDrawable": f"@drawable/os_cursor_{n}"}.items():
            ET.SubElement(field, "item", name=attr).text = val
        result[f"app/src/main/res/drawable/os_field_{n}.xml"] = (
            '<shape xmlns:android="http://schemas.android.com/apk/res/android">'
            f'<solid android:color="{c["control"]}"/><corners android:radius="20dp"/>'
            '<padding android:left="16dp" android:top="10dp" android:right="16dp" android:bottom="10dp"/></shape>\n')
        result[f"app/src/main/res/drawable/os_cursor_{n}.xml"] = (
            '<shape xmlns:android="http://schemas.android.com/apk/res/android">'
            f'<solid android:color="{c["accent"]}"/><size android:width="2dp"/></shape>\n')
    ET.indent(res)
    result["app/src/main/res/values/os_themes.xml"] = '<?xml version="1.0" encoding="utf-8"?>\n' + ET.tostring(res, encoding="unicode") + "\n"
    apps = " \\\n    ".join(edition["apps"])
    result["os/wallpaper/src/main/res/values/config.xml"] = (
        f'<resources><integer name="grapefruit_default_theme">{edition["default_theme"]}</integer></resources>\n')
    result["os/products/edition.mk"] = (
        "# Generated by os/tools/generate.py. SPDX-License-Identifier: Apache-2.0\n"
        f"PRODUCT_SYSTEM_DEFAULT_PROPERTIES += ro.grapefruit.edition={edition['edition']}\n"
        f"PRODUCT_PACKAGES += {apps}\n")
    manifest_source = ET.parse(ROOT / "os/wallpaper/src/main/AndroidManifest.xml").getroot()
    ET.register_namespace("android", "http://schemas.android.com/apk/res/android")
    manifest_source.set("package", "io.github.hayliewordsman.grapefruitwallpaper")
    manifest_source.set("{http://schemas.android.com/apk/res/android}versionCode", "1")
    manifest_source.set("{http://schemas.android.com/apk/res/android}versionName", "0.1-dev")
    ET.indent(manifest_source)
    result["os/wallpaper/AndroidManifest.xml"] = ET.tostring(manifest_source, encoding="unicode") + "\n"
    result["os/overlay/common/frameworks/base/core/res/res/values/grapefruit_config.xml"] = (
        f'<resources><integer name="config_grapefruitDefaultTheme">{edition["default_theme"]}</integer></resources>\n')
    result.update(keyboard_outputs())
    lock = json.loads((ROOT / "os/upstream.json").read_text())
    manifest = ET.Element("manifest")
    ET.SubElement(manifest, "remote", name="grapefruit", fetch="https://github.com/")
    ET.SubElement(manifest, "project", name="hayliewordsman/grapefruitmusic",
                  path="vendor/grapefruit", remote="grapefruit", revision="refs/heads/" + edition["branch"])
    for project, info in lock["projects"].items():
        ET.SubElement(manifest, "extend-project", name="platform/" + project, revision=info["revision"])
    ET.indent(manifest)
    result["os/manifests/grapefruit.xml"] = ET.tostring(manifest, encoding="unicode", xml_declaration=True) + "\n"
    return result


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--check", action="store_true")
    args = p.parse_args()
    different = []
    for path, content in outputs().items():
        target = ROOT / path
        if args.check:
            if not target.exists() or target.read_text() != content:
                different.append(path)
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content)
    if different:
        raise SystemExit("Regenerate stale files: " + ", ".join(different))


if __name__ == "__main__":
    main()
