"""Fit an all-pole crowd texture model to original procedural voices/applause.
No downloaded recordings, pretrained weights, or third-party voices are used.
"""
import hashlib, json
from pathlib import Path
import numpy as np
ROOT = Path(__file__).resolve().parents[2]
RATE, ORDER = 8000, 12

def example(seed):
    rng = np.random.default_rng(seed)
    t = np.arange(RATE * 2) / RATE
    x = np.zeros(len(t))
    for _ in range(24):
        f0 = rng.uniform(95, 310)
        phase = rng.uniform(0, 2*np.pi)
        formants = rng.uniform([350, 1100, 2200], [850, 2000, 3300])
        voice = np.zeros(len(t))
        for harmonic in range(1, int(3800/f0)):
            f = harmonic*f0
            weight = sum(np.exp(-0.5*((f-formants)/180)**2)) / harmonic
            voice += weight*np.sin(2*np.pi*f*t + phase*harmonic)
        envelope = np.maximum(0, np.sin(2*np.pi*rng.uniform(1, 4)*t + phase))**2
        x += voice*envelope
    # Original synthetic applause: short independent noise bursts, no samples.
    for _ in range(30):
        start = int(rng.integers(0, len(t)-800))
        x[start:start+800] += rng.normal(size=800)*np.exp(-np.arange(800)/90)*0.4
    return x / max(np.std(x), 1e-8)

train_seeds=list(range(4100, 4124))
test_seeds=list(range(5100, 5108))
clips=[example(s) for s in train_seeds]
corr=np.array([sum(np.dot(x[k:], x[:len(x)-k]) for x in clips) for k in range(ORDER+1)])
matrix=np.array([[corr[abs(i-j)] for j in range(ORDER)] for i in range(ORDER)])
coef=np.linalg.solve(matrix + np.eye(ORDER)*corr[0]*1e-5, corr[1:])
# Bound poles for stable real-time synthesis, including float rounding.
poles=np.roots(np.r_[1, -coef]); poles *= np.minimum(1, 0.97/np.abs(poles))
coef=-np.poly(poles).real[1:]
def error(x):
    pred=sum(coef[k-1]*x[ORDER-k:len(x)-k] for k in range(1, ORDER+1))
    return float(np.mean((x[ORDER:]-pred)**2)/np.mean(x[ORDER:]**2))
innovation=float(np.sqrt(np.mean([error(x) for x in clips])))
java='''// Generated by tools/live/train.py; SPDX-License-Identifier: GPL-3.0-or-later
package com.grapefruitmusic.playback;
final class LiveCrowdModel {
    static final int RATE = 8000;
    static final double[] AR = {%s};
    static final double INNOVATION = %.12g;
    private LiveCrowdModel() { }
}
''' % (', '.join('%.12g'%v for v in coef),innovation)
path=ROOT/'app/src/main/java/com/grapefruitmusic/playback/LiveCrowdModel.java'
path.write_text(java)
manifest=dict(name='Procedural crowd AR-12 v1',license='GPL-3.0-or-later',data='Original procedural choir and applause; no recordings',sample_rate=RATE,train_seeds=train_seeds,evaluation_seeds=test_seeds,selection_seeds=[],numpy=np.__version__,script_sha256=hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),model_sha256=hashlib.sha256(java.encode()).hexdigest(),max_pole_radius=float(max(abs(poles))),train_prediction_error=float(np.mean([error(x) for x in clips])),held_out_prediction_error=float(np.mean([error(example(s)) for s in test_seeds])),limitations='Synthetic spectral prediction metric only; no real-crowd or perceptual validation. The AR model makes texture, not intelligible singing. Song-derived vocal doubling supplies singalong.')
(ROOT/'app/src/main/assets/live_training.json').write_text(json.dumps(manifest,indent=2)+'\n')
print(json.dumps(manifest,indent=2))
